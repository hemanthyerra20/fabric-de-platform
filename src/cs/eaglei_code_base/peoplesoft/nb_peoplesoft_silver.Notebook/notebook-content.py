bronze_base_path = "abfss://f2aea860-156d-4e18-b078-1356be7161de@onelake.dfs.fabric.microsoft.com/0277ffad-3784-4551-8d7d-66d1b8ff633a/Tables"

silver_base_path = "abfss://f2aea860-156d-4e18-b078-1356be7161de@onelake.dfs.fabric.microsoft.com/08846ef1-977d-4698-b06f-84fdbd834bc6/Tables"

from datetime import datetime
run_id = datetime.utcnow().strftime("%Y%m%d%H%M%S")

results = []

for table_name in allowed_tables:
    table_name = str(table_name).upper()

    bronze_path = f"{bronze_base_path}/peoplesoft/{table_name}"
    silver_path = f"{silver_base_path}/peoplesoft/{table_name}"

    print("\n===================================")
    print(f"START TABLE : {table_name}")
    print(f"Reading     : {bronze_path}")

    try:
        # Read Bronze table
        df = spark.read.format("delta").load(bronze_path)
        source_count = df.count()

        # Drop known audit columns if they exist
        audit_cols = ["run_id", "createdby", "created_timestamp"]
        existing_cols = [c for c in audit_cols if c in df.columns]
        if existing_cols:
            df = df.drop(*existing_cols)

        # Add Silver audit columns
        df = (
            df
            .withColumn("run_id", lit(str(run_id)))
            .withColumn("createdby", lit("ADF_Pipeline"))
            .withColumn("created_timestamp", current_timestamp())
        )

        print(f"Writing     : {silver_path}")

        (df.write
            .format("delta")
            .mode("overwrite")
            .option("overwriteSchema", "true")
            .save(silver_path)
        )

        # Validate counts
        target_count = spark.read.format("delta").load(silver_path).count()

        print(f"Table Name   : {table_name}")
        print(f"Source Count : {source_count}")
        print(f"Target Count : {target_count}")
        print("STATUS       : SUCCESS")

        results.append({
            "table": table_name,
            "status": "SUCCESS",
            "source_count": source_count,
            "target_count": target_count,
        })

    except Exception as e:
        print(f"Table Name   : {table_name}")
        print(f"STATUS       : FAILED")
        print(f"ERROR        : {e}")

        results.append({
            "table": table_name,
            "status": "FAILED",
            "error": str(e),
        })

print("\n========== SUMMARY ==========")
for r in results:
    if r["status"] == "SUCCESS":
        print(f"{r['table']}: SUCCESS (source={r['source_count']}, target={r['target_count']})")
    else:
        print(f"{r['table']}: FAILED ({r['error']})")
print("============================")


